#!/usr/bin/env python3
"""屋里的台词也不许有文言和行话。

台词有三套源，各自独立:
  · `villager_line`（村子首页那句「今天说」）—— check-villager-lines.py 管
  · 界面文案（wxml）—— check-plain-words.py 管
  · **屋里的气泡**（rooms/src/rooms/*.js 的 `say:` / `lines:`）—— 从前没人管

第三套恰恰是用户看得最久的:点进屋子，村民头顶自动一句一句地冒。
2026-09-01 五路评审在这儿抓到一整片:丹增说了三次「贫僧」，
沈砚「此字」「恕我直言」，阿云「此卦大吉」「此局何解」，
桃桃把「休门」说了三遍 —— 而「休门」正是结果屏明令一个都不留的那个词。

判据跟另外两支同一套词表，只是扫的文件不同;注释里讨论这些词是允许的。
"""
import re, sys, pathlib

根 = pathlib.Path(__file__).resolve().parent.parent
# 【扫三处，不是一处】。原先只 glob `rooms/src/rooms/*.js` —— 七个文件。
# 而屋里的家具台词大半在 `rooms/src/assets/*.js`（十二个文件），
# 村图上的吆喝与对话在 `rooms/src/engine/village.js`。
# 2026-09-02 实测:那两处合计 28 处「贫道」「无量天尊」「道长」，
# 词表里明明有「贫道」，这一支却一路报绿 —— 它够不着。
屋 = (sorted((根 / 'rooms/src/rooms').glob('*.js'))
      + sorted((根 / 'rooms/src/assets').glob('*.js'))
      + [根 / 'rooms/src/engine/village.js'])
屋 = [f for f in 屋 if f.exists()]
if len(屋) < 15:
    print(f'✗ 只扫到 {len(屋)} 个文件 —— 目录搬过家而这一支没跟上'); sys.exit(1)

文言 = ['贫道', '贫僧', '老衲', '小生', '足下', '尔等', '此字', '此卦', '此局',
        '无量天尊', '道长', '善哉', '施主', '道友',
        '何解', '恕我直言', '不宜', '窃以为', '不才', '愚见', '大吉大利']

# 【这几个词裸着匹配会误伤】。词表其余的项在现代汉语里没有别的用法，
# 裸子串就够;下面这几个有 —— 「我的在下面」不是文言自称「在下」，
# 「今日份的开心」也不是历书那个「今日」。
#
# 收的是【认词的方式】，不是【规则的覆盖面】—— 真违规的写法照样红，
# 所以这是修 bug，不是开例外。区别就在下面那张反证表上:
# 没有反证的「精确化」跟例外表没有分别，下一个人把正则改松了没人知道。
文言正则 = {
    '在下': r'在下(?![面方边头层侧])',        # 在下面 / 在下方 / 在下边……
    '今日': r'今日(?![份常])',                # 今日份 / 今日常……
}
自检 = [
    ('在下不才，献丑了', True),               # 真的文言自称 —— 必须红
    ('师父的那把在上面，我的在下面', False),   # 方位短语 —— 不许红
    ('今日甲子……月将在亥', True),            # 历书原文 —— 必须红
    ('今日无事，晒晒太阳', True),            # 【只靠「今日」触发】。少了这一条，
                                            #  把正则收成 `今日(?=甲)` 也能一路绿 ——
                                            #  实测过，2026-09-02 变异测试当场溜过去了
    ('今日份的懒', False),                    # 现代口语 —— 不许红
]
行话 = ['三奇六仪', '值符', '休门', '生门', '伤门', '杜门', '景门', '死门', '惊门', '开门',
        '紫微', '天府', '命盘', '断语', '起局', '起课', '排盘', '大六壬', '奇门遁甲',
        '梅花易数', '八字', '日主', '用神', '格局']

# 只看真的会显示出来的字符串:say / lines / labels
串 = re.compile(r"(?:say|pSay|labels|lines)\s*:\s*(\[[^\]]*\]|'(?:[^'\\]|\\.)*')", re.S)
错, 条数 = [], 0
for f in 屋:
    源 = f.read_text(encoding='utf-8')
    # 整块注释挖掉 —— 里面讨论这些词是允许的（换成等长空白，行号不漂）
    净 = re.sub(r'/\*.*?\*/', lambda m: re.sub(r'[^\n]', ' ', m.group(0)), 源, flags=re.S)
    净 = re.sub(r'//[^\n]*', lambda m: ' ' * len(m.group(0)), 净)
    for m in 串.finditer(净):
        for 句 in re.findall(r"'((?:[^'\\]|\\.)*)'", m.group(1)):
            if not 句:
                continue
            条数 += 1
            行 = 净[:m.start()].count('\n') + 1
            for 词 in 文言 + list(文言正则):
                if (re.search(文言正则[词], 句) if 词 in 文言正则 else 词 in 句):
                    错.append(f'{f.name}:{行}　文言「{词}」：{句}')
            for 词 in 行话:
                if 词 in 句:
                    错.append(f'{f.name}:{行}　行话「{词}」：{句}')
            if re.search(r'[一-龥][,?!;:]|[,?!;:][一-龥]', 句):
                错.append(f'{f.name}:{行}　半角标点：{句}')

if 条数 < 40:
    print(f'✗ 只抠出 {条数} 句台词 —— 六间房不该这么少，这一支多半在空转')
    sys.exit(1)

# 【反证先跑】。上面那两条正则是「把误伤收掉」，而收得过头就成了放水，
# 且放水后这一支照样报绿 —— 跟没有它一样。所以边界写成可执行的:
# 真违规的四个字喂进去必须红，误伤的四个字喂进去必须不红。
# 【词表被删一项，前面那几条反证抓不到】。它们只钉住两个歧义词的边界;
# 而语料一旦干净，删掉「贫道」这一项什么都不会变 —— 2026-09-02 实测溜过去了。
# 拿词表自己去检自己也没用(删掉的那项根本不在遍历里，同日实测同样溜过去)。
# 要一个【独立于词表】的证人:下面这张底线表，每一条都记着它是怎么进来的。
# 删词表 = 删不掉底线 = 当场红;真要删，得两处一起改，diff 上看得见。
底线 = {
    '贫道':   '阿云的自称，2026-09-02 在村图与素材里 28 处',
    '无量天尊': '同上，村图 bark 一处',
    '道长':   '同上，村民对他的称呼两处',
    '贫僧':   '丹增，2026-09-01 二轮评审抓到三处',
    '此卦':   '阿云「此卦大吉」，同上',
    '此字':   '沈砚，同上',
    '休门':   '桃桃说了三遍，而结果屏明令一个不留',
    '今日':   '阿云历书「今日甲子」，2026-09-02',
    '在下':   '同日;它同时是「我的在下面」的误伤源，见上面的正则',
    '起课':   '阿云屋里三处，2026-09-02 五路评审判「改台词，不开例外」',
    '排盘':   '白鹭屋里两处，同上',
    '紫微':   '白鹭屋里两处，同上',
    '起局':   '桃桃屋里两处，同上',
    '梅花易数': '沈砚屋里一处，同上;名册页同款用法早有判例',
}
缺 = [w for w in 底线 if w not in 文言 and w not in 行话 and w not in 文言正则]
if 缺:
    for w in 缺:
        print(f'✗ 底线词「{w}」不在词表里了 —— 它是{底线[w]}')
    print('  往词表里删词不能让这一支闭嘴:要删得连底线一起删，并说清为什么')
    sys.exit(1)

for 句, 该红 in 自检:
    红 = any(re.search(文言正则[词], 句) if 词 in 文言正则 else 词 in 句
             for 词 in 文言 + list(文言正则))
    if 红 != 该红:
        print(f'✗ 反证不成立：「{句}」{"该红却没红" if 该红 else "不该红却红了"}'
              ' —— 词表或正则被改松/改紧了，先修它')
        sys.exit(1)
for e in dict.fromkeys(错):
    print('  ✗ ' + e)
print(('✗ ' if 错 else '✓ ') + f'屋里的台词说的是人话 · {len(屋)} 间房 · {条数} 句')
sys.exit(1 if 错 else 0)

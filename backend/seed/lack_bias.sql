-- 偏向层:每个「缺」把中性结论往哪个方向偏。
--
-- 这不是写文案,是分类:一个缺什么的人,会不由自主地劝你去补那一样。
-- 缺勤快的阿云偏「该动了」,缺静的丹增偏「该停了」—— 工序单举的就是这两个例子。
-- （这个词原本是「勤」，读者一眼读成「缺勤」——旷工、考勤扣钱。
--   二十五个单字里只有它会连读成现成的词，2026-08-31 换成两个字。）
-- 七个方向:
--   move   该动了      still  该停了      keep   该守着     let_go 该放下
--   ask    该问问      near   该走近      wait   该等等
--
-- 40 个缺各不相同(这是设计的核心:术数会重叠,缺不会),所以这里正好 40 行。
-- note 那一列写的是「为什么是这个方向」—— 给后来想改它的人看,
-- 不写的话这张表过半年就变成一堆没人敢动的魔法值。


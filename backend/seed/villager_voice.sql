--         寺里让他下山练完一百零八式再回来,这句是真的
--   白鹭  ✗ 改了。原本没有收尾,通篇只剩判词。补上她自己的设定原话
--         「我只念,不改」—— 冷是人设,但她从不主张自己能改你的命

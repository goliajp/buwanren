--   婆婆  「乖,拿颗糖哦」是慈爱不是俯视,不动
--   米拉  「小家伙」是角色卡明写的口头禅(称呼【所有人】),不是对你俯视,不动
--   丹增  ✗ 改了。原本「记住:」+「就这样,去吧」—— 一句命令一句打发,

-- 声音层模板 —— 照设计册里已经写定的说话风格来,不另造人设。
--
-- ★ 只给这几位写,不批量凑 40 份。说话模板是角色的一部分,该跟他那间房
--   一起做、一起验收;一次凑齐等于把最要紧的东西做成填空题。
--   没模板的村民问签会明确报错,不会拿别人的口气搪塞。
--
-- 现有七位 = 已建好房的六间 + 米拉(她与婆婆同修塔罗、缺不同,
-- 是工序单门禁「同门不同缺给出不同解读」那条要用的一对)。
--
-- 标点按项目规矩:中文全角,台词结尾不加句号。
--
-- ★ closer 必须以标点开头(「。」或「……」)。它接在「忌 xx」后面,
--   不带标点就会粘成一句:「忌动土就这样」。由 villager_reading_use_cases
--   里的 every_closer_starts_with_punctuation 钉住。


-- 台词修正 · 2026-09-01
--
-- 五路评审各自独立挑出来的四处。不是「润色」——每一条都有具体的坏处。

-- 一、阿云:一句文言、一句行话，两条都撞硬要求
--
-- 「起局要静」:起局是奇门的说法，而阿云会的是大六壬 —— 行话本身
--   已经不许上界面，何况还是【别人门里的】行话。他在屏幕上做的动作
--   是掐指算，那就写掐指。
-- 「贫道」:文言。硬要求写着「完全不允许有任何文言古书的表达」，
--   只有说明书的专业细节里例外，而这是气泡台词。
UPDATE villager_line SET text = '掐指要静。你现在太吵了'
 WHERE villager_id = 'ayun' AND seq = 2;
UPDATE villager_line SET text = '我不算命。我就看看，看完你自己拿主意'
 WHERE villager_id = 'ayun' AND seq = 4;

-- 二、卢恩与木一是同一个匠人
--
-- 木一（钟表匠·缺信）:「齿轮不骗人」「我信这只表。别的，你说了我记着」
-- 卢恩（刻符的·缺笑）:「说出来的会变。刻下来的不会」「答应过的事，石头替我记着」
-- 两个人都在说「我信这个物件，不信人说的话」。木一缺的就是信，
-- 这个主题是他的身份;卢恩缺的是笑，物件替他记事只是顺带。
-- 所以让卢恩这一条搬开 —— 换成他这门手艺的身体感觉，
-- 北地、冷、手僵，一个木一不可能说的角度。
UPDATE villager_line SET text = '北边冷。手冻僵了，刻出来的反而稳'
 WHERE villager_id = 'rune' AND seq = 3;

-- 三、「这句是……的」三个人在用
--
-- 赛博「这句是认真的」/ 玄冥「这句是好话」/ 小满「这句是学婆婆的」。
-- 三个人共用一个语癖，读起来就是同一个作者在说话 —— 而这正是
-- 「四十位是批量生成的」这件事露馅的地方。
-- 留两个:赛博缺温度，给自己的真心加标注是他这个缺的机制本身;
-- 小满那句是【出处】不是【语气标注】，是另一个动作，而且是她的笑点。
-- 玄冥那句跟赛博是同一个动作（给上一句标注语气），改掉他的。
-- 他缺的是人 —— 让这一句直接把那个缺说出来，比反讽更疼。
UPDATE villager_line SET text = '一个人待了九年。下山就为看看人还在不在'
 WHERE villager_id = 'xuanming' AND seq = 3;

-- 四、莉莉丝整组只有一个调门
--
-- 「镜子里那个不是你」「我没有影子」「看久了它会先眨眼」「你身后那一片，
-- 跟着你很久了」—— 四句全是同一种不祥的宣告，没有一句让人想跟她说话。
-- 这个村子的调门是平易、亲和、带点搞笑，怪可以，但要【可爱的怪】。
-- 第三句最像恐怖片、且关于她自己什么都没说，换掉它:
-- 照镜子的人天生就该最先看见你今天哪里不对 —— 这是她的本事，
-- 用在一件顶小的事上，她就从鬼变成了人。
UPDATE villager_line SET text = '你头发翘起来了。左边。……我不是故意看的'
 WHERE villager_id = 'lilith' AND seq = 3;

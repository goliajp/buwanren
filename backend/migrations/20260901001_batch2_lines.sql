-- 又八位的台词。手法照旧:
--
--   缺的那样东西要长在【语言的形状】里，不在台词的内容里。
--
-- 先定死「这个人怎么说话」（语速 / 句子完不完整 / 说给谁听），再定他说什么。
-- 这三格的组合，四十位里不许撞 —— 从「缺什么」直接写台词，
-- 写出来的必然是感想，四十份感想彼此不隔。
--
-- 检验:把四十位的台词洗牌、抹掉名字，随手抽一条认不出是谁的，那位回炉。


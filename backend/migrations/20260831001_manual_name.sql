-- 「那一份」不是名字，是指代。
--
-- 术语清干净之后，这个产品在屏上的说法变成了「那一份」「看完整的那一份」
-- 「读你的那一份」—— 而指代要有上下文才成立，第一次看见它的人没有上下文，
-- 于是它什么都没说。后端这一侧的名字则还停在术语时代：
--   八字深度报告 · 日主旺衰 + 格局 + 用神 + 大运 + 流年
-- 那一行副标题整句都是屏上不许出现的词（0830 定：术语只留在正文的
-- 专业细节里，不上标题、不上商品卡）。
--
-- 定名【你的说明书】：说清了它是什么（一份讲你怎么运作的东西），
-- 零玄学，一眼懂，而且把人写成说明书这件事本身有点意思。
UPDATE product
   SET name = '你的说明书',
       sub_title = '你缺什么、这些年怎么走 —— 一次说完'
 WHERE code = 'naji_deep';

UPDATE sku
   SET name = '你的说明书'
 WHERE code = 'naji_deep_default';


-- 五位的台词。手法定下来了，写法是：
--
--   缺的那样东西要长在【语言的形状】里，不在台词的内容里。
--
-- 阿罗（缺胆）从不说「我很胆小」——他的怯长在断句和单音里。但那一招
-- 不能推广：句法残缺跟怯懦几乎同构，对他天然成立，对别人不成立。
-- 四十位全用省略号和半截句，缺的东西各不相同、演法却成了同一个人，
-- 玩家读到第七八位就会觉得「这村子的人都有社恐」——这正是「不完人」
-- 这个设定最经不起的误读。
--
-- 所以先定死【这个人怎么说话】（语速 / 句子完不完整 / 说给谁听），
-- 再定他说什么。这三格的组合，四十位里不许撞。
--
-- 检验：把四十位的台词洗牌、抹掉名字，随手抽一条，认不出是谁的，
-- 那位回炉。


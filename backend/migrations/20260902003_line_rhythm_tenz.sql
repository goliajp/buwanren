-- 台词节奏（一）· 丹增 —— 先做一位，手法验过再往下
--
-- 【问题】。第二轮评审说「160 句里 113 句是同一个两拍句式」，我当时量错了
-- 语料（量的是村图上的 255 条 bark）也量错了形状（按「恰好一个逗号」去数），
-- 得出四成、判它不成立。2026-09-02 复核:那批台词真正的形状是
-- 「短陈述。展开」—— `^[^。？！]{2,12}。[^。]+$` 实测 **107/160 = 66.9%**。
-- 评审是对的。
--
-- 【真正伤人的不是那 67%，是它在一个人身上的密度】。
-- 村主屏一天只显示一条，从这位村民的四条里等概率挑。
-- 实测:8 位村民四条【全是】这个形状，19 位是四中之三 ——
-- 也就是 27 个人，你连着三四天听到的是同一个节奏。
-- 目标定成【一人四条里同一句式不超过两条】，可机械核对。
--
-- 【不是把句子改差】。这些句子单看都好，「短陈述。展开」本身也没错，
-- 错的是一个人从头到尾只用它。所以改的是【节奏】，不是内容:
-- 该连起来说的连起来，该喊的喊出来。

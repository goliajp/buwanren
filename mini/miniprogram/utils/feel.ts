/* 手感 —— 一次点击该有的那点回应（设计册 0830 §4）。
 *
 * 游戏和普通 app 的差别不在画得多漂亮，在于【你碰它，它有反应】。
 * 震动是手机上最便宜的一档高级感:一行代码，而少了它整个产品会显得"平"。
 *
 * 三档按 0830 §4.3 那张表分:
 *   轻 —— 点一下就走的（按按钮、点一格、切页签）
 *   中 —— 一件事成了（下单、付款、填完生辰）
 *   重 —— 高光时刻（扫开御守、有人住进来）
 *
 * 失败一律吞掉:用户没开系统震动、或者机型不支持时，
 * **不能因为震不了就让主流程挂掉** —— 它是锦上添花，不是功能。
 */

function 震(type: 'light' | 'medium' | 'heavy'): void {
  try {
    wx.vibrateShort({ type, success() {}, fail() {}, complete() {} })
  } catch {
    /* 震不了就算了 —— 见上 */
  }
}

/** 点一下就走的:按钮、一格宅基、页签 */
export const 轻 = (): void => 震('light')
/** 一件事成了:下单、付款、生辰填完 */
export const 中 = (): void => 震('medium')
/** 高光:扫开御守、有人住进来 */
export const 重 = (): void => 震('heavy')

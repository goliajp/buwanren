/**
 * 「几点点香」这句话怎么写 —— 由后端那份排期算出来，不写死在屏上。
 *
 * 后端把它做成了配置（`UNMEI_INCENSE_WEEKDAY` / `HOUR` / `MINUTES`，
 * 见 `routes/incense.rs` 顶上那段）：运营想把它从周四晚九点挪到
 * 周三晚八点，不该改代码重新发版。
 *
 * 而在这之前，屏上有四句话把它写死了 ——
 * 一味香那一屏两句、村口那一屏两句，全是「周四晚九点」。
 * 也就是说**挪了时间之后，后端在别的时刻开场，屏上还在叫人周四来**：
 * 两处都不报错，都还绿着，只是那句话从此是假的。
 * 这一轮就是这样撞见的：验证跑在一个把窗口挪到凌晨四点的实例上，
 * 屏上照旧写着「今晚九点已经开始了」，而断言对的是它自己那份写死的字。
 *
 * 两句的分别：
 * - `那一天那一刻()` —— 不到点时说的那句里的时刻，「周四晚九点」
 * - `今天那一刻()`   —— 到点时说的那句里的时刻，「今晚九点」
 *
 * 后半句（「村里一起点一支」/「苏合在院子里点香」）留在各自的 wxml 里，
 * 因为那是两屏各自的口气，不是同一句话。
 */

import type { IncenseSchedule } from '../services/incense'

const 周词 = ['周一', '周二', '周三', '周四', '周五', '周六', '周日']

/* 钟点用汉字，跟屏上别处一致。下标是 `hour % 12`：
   0 点与 12 点都落到「十二」，其余就是本身。
   两点写「两」不写「二」—— 「下午二点」没人这么说。 */
const 钟点词 = ['十二', '一', '两', '三', '四', '五', '六', '七', '八', '九', '十', '十一']

/* 一天里的段。前一列进「周四__九点」，后一列进「__九点已经开始了」。
   分界照口语来：九点以前是早上，十二点前后是中午，六点以后是晚上。 */
function 哪一段(h: number): { 前: string; 今: string } {
  if (h === 0) return { 前: '半夜', 今: '今天半夜' }
  if (h < 6) return { 前: '凌晨', 今: '今天凌晨' }
  if (h < 9) return { 前: '早', 今: '今天早上' }
  if (h < 12) return { 前: '上午', 今: '今天上午' }
  if (h < 13) return { 前: '中午', 今: '今天中午' }
  if (h < 18) return { 前: '下午', 今: '今天下午' }
  return { 前: '晚', 今: '今晚' }
}

/* 这三个数是从网上来的 —— 越界的话下标取出来是 undefined，
   而 undefined 会原样印到屏上（「undefined晚九点」）。
   这是信任边界，不是内部防御。 */
function 收进范围(n: number, 下: number, 上: number): number {
  return Number.isFinite(n) ? Math.min(上, Math.max(下, Math.trunc(n))) : 下
}

function 钟点(h: number): string {
  return 钟点词[收进范围(h, 0, 23) % 12] + '点'
}

/** 「周四晚九点」—— 不到点时那句话里的时刻 */
export function 那一天那一刻(p: IncenseSchedule): string {
  return 周词[收进范围(p.weekday, 0, 6)] + 哪一段(收进范围(p.hour, 0, 23)).前 + 钟点(p.hour)
}

/** 「今晚九点」—— 到点时那句话里的时刻 */
export function 今天那一刻(p: IncenseSchedule): string {
  return 哪一段(收进范围(p.hour, 0, 23)).今 + 钟点(p.hour)
}

/* 头像占位的「脸纹」。

   四十张立绘还没画，现在是「圆底 + 姓名末字」。底色按 `lack_bias` 的
   方向分七档 —— 那是有意的，颜色本身在说「他劝你往哪走」。

   但缺「近人」那一路有十一位:名册上十一个一模一样的粉橙圆牌并排摆着，
   占位感最重的就是这一屏。同色之内换渐变角度（六档），
   颜色仍然在说方向，人却分得开了。

   由 id 定，不由列表下标定 —— 同一个人在名册、村子、他的主页、
   搬进来那一刻必须是同一张脸;按下标算的话，他在每个列表里都不一样。

   【现状】名册上「没来」那一段是刻意的灰白（还没请来的人就该灰着），
   所以脸纹只在「能请」那一段生效;而那一段眼下只有四位、各不同色，
   看不出效果。缺「近人」那十一位大多还没上架 —— 上架就会撞在一起。 */
export function 脸纹(id: string): string {
  let h = 0
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0
  return 'fa-' + (h % 6)
}

/* 一整列一起分档。单看 id 做散列的话分布是碰运气的 ——
   缺「近人」那一路十一位，实测六档里有一档占了四位、有一档一个都没有，
   而并排的两位撞上同一档就白做了。

   这里按【同一方向内的出场顺序】轮着发:同色的人一定相邻不同档，
   而且十一位铺满六档。同一个人在不同列表里档位可能不同 ——
   但同一屏上他只出现一次，要紧的是「这一屏上分得开」。 */
export function 一列脸纹<T extends { direction?: string | null }>(列: T[]): string[] {
  const 数: Record<string, number> = {}
  return 列.map((x) => {
    const d = x.direction || ''
    数[d] = (数[d] || 0) + 1
    return 'fa-' + ((数[d] - 1) % 6)
  })
}

/* 日子说给人听的写法。
 *
 * 「八月三十 · 周日」——「2026-08-30」是给系统读的，
 * 中文数字才是说给人听的（设计册 0830 §5）。
 *
 * 抽出来是因为它先在两屏各写了一份，而其中一份写成了 ISO ——
 * 同一个产品对同一天两种说法，翻过去翻回来就露馅。
 * 记录类的日期（下单、寄出）照旧用数字：那是台账，不是招呼。
 */
const 汉数 = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十']

export function 汉日(n: number): string {
  if (n <= 10) return 汉数[n]
  if (n < 20) return '十' + 汉数[n - 10]
  if (n === 20) return '二十'
  if (n < 30) return '二十' + 汉数[n - 20]
  if (n === 30) return '三十'
  return '三十' + 汉数[n - 30]
}

export function 今天几号(d: Date): string {
  const 周 = ['日', '一', '二', '三', '四', '五', '六'][d.getDay()]
  return `${汉日(d.getMonth() + 1)}月${汉日(d.getDate())} · 周${周}`
}

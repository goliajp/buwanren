/* 一张表在「取不到」时该有的那一行。
 *
 * 【取不到跟「一条都没有」不是一回事】（2026-09-03 五路评审 · 后台产品体验）。
 * 上一版每张表只有空态那一行，而它的条件是 `X.data && …length === 0` ——
 * 查询失败时 `data` 是 undefined，两行都不渲染，
 * 屏上剩一张只有表头的空表。带着筛选条件的页面上，
 * 运营会以为是自己把条件筛空了。
 *
 * 做成一个组件而不是十九处各写一遍：这句话将来要改的时候，
 * 十九处里漏掉一处不会有任何东西发现 —— 今天这个洞本身就是
 * 「同一件事在很多处各写各的」长出来的。
 */
export default function TableError({ 出错, 列数 }: { 出错: boolean; 列数: number }) {
  if (!出错) return null;
  return (
    <tr>
      <td colSpan={列数} className="text-center py-10 text-debt">
        取不到 —— 别把这张空表当成「一条都没有」
      </td>
    </tr>
  );
}
